#!/usr/bin/env python3
"""Regenerate the hash-pinned Piper locks from ``PIPER_TTS_VERSION`` (SPEC 4A, Installer).

Resolves with ``uv pip compile`` for each target in ``roboemot.install.piper_lock.TARGETS``
without installing anything locally (wheels only, so no build step runs). Needs ``uv``.
"""

from __future__ import annotations

import subprocess
import sys
import tempfile
from pathlib import Path

from roboemot.install import PIPER_TTS_VERSION
from roboemot.install.piper_lock import LOCK_DIR, TARGETS, lock_name


def compile_lock(arch: str, python: str, uv_platform: str) -> str:
    """The lock text for one target: uv's resolution with hashes, under a short header."""
    with tempfile.TemporaryDirectory() as tmp:
        spec = Path(tmp) / "piper.in"
        spec.write_text(f"piper-tts=={PIPER_TTS_VERSION}\n")
        cmd = [
            "uv", "pip", "compile", str(spec), "--generate-hashes", "--no-header", "--no-build",
            "--python-platform", uv_platform, "--python-version", python, "--quiet",
        ]  # fmt: skip
        out = subprocess.run(cmd, check=True, capture_output=True, text=True).stdout
    header = (
        f"# Generated by scripts/lock_piper.py for piper-tts=={PIPER_TTS_VERSION} on {arch}, "
        f"Python {python} (uv {uv_platform}). Do not edit.\n"
    )
    return header + out


def main() -> int:
    LOCK_DIR.mkdir(parents=True, exist_ok=True)
    for (arch, python), uv_platform in sorted(TARGETS.items()):
        path = LOCK_DIR / lock_name(arch, python)
        path.write_text(compile_lock(arch, python, uv_platform))
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
