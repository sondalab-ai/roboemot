#!/usr/bin/env python3
"""Synthesize Reachy Mini's non-verbal cue sounds (SPEC 8, Non-verbal cues; SPEC 4A).

The sounds are made here, not copied: each is a "blirp" of RoboEmot's own self-soothing synth
(``roboemot.soothe.synth``, SPEC 7B) with a fixed shape and seed, rendered at 16 kHz and written
as 16-bit mono WAV into ``data/cues/`` of ``roboemot_reachymini`` with ``VENDORED.json`` (how each
was made, its sha256). Each is under 1 s and peaks at -18 dBFS before the runtime's
``voice.cues.volume_db``.

``listening`` is the exception: a blip, one rising chirp of the same synth (``render_blirp`` of a
one-event plan, no seed), 100 ms at -30 dBFS, 12 dB under the other cues (-36 dBFS as played
with the default ``voice.cues.volume_db``). It says "I heard you". Its length is tied to
``voice.vad.min_speech_ms`` (default 200 ms): ``SpeechOutput.play_aside`` refuses a sound that is
not shorter (logged once, counted ``aside.too_long``), so the robot never takes its echo for
speech, and a robot configured with ``min_speech_ms`` of 100 ms or less gets no blip (SPEC 8,
Non-verbal cues).

    python scripts/make_cue_sounds.py           # write the WAVs and VENDORED.json
    python scripts/make_cue_sounds.py --check   # offline: the WAVs match a fresh render

The seeds were picked once for the shape of each sound (event kinds in order): not_heard a
falling then a rising chirp (a "hm?"), fallback two falling chirps, offline a warble then a
falling chirp. These numbers are constants of this script, not configuration.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import random
import sys
import wave
from pathlib import Path

import numpy as np
from roboemot.config.schema import SoundShape
from roboemot.soothe.synth import (
    BlirpEvent,
    BlirpPlan,
    db_to_gain,
    plan_blirp,
    render_blirp,
    synthesize,
)

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "packages/roboemot-reachymini/src/roboemot_reachymini/data/cues"
RATE_HZ = 16000
GAIN_DB = -18.0
PCM_FULL_SCALE = 32767
CHECK_TOLERANCE = 2  # 16-bit steps a fresh render may differ by (float rounding across machines)
BLIP = {"event": "chirp_up", "f0_hz": 660.0, "f1_hz": 990.0, "length_s": 0.1, "gain_db": -30.0}
CUES = {
    "listening": BLIP,
    "not_heard": {"seed": 167, "pitch_hz": 440.0, "tempo_bpm": 100.0, "length_s": 0.5},
    "fallback": {"seed": 2, "pitch_hz": 330.0, "tempo_bpm": 90.0, "length_s": 0.6},
    "offline": {"seed": 77, "pitch_hz": 260.0, "tempo_bpm": 80.0, "length_s": 0.7},
}


def shape(spec: dict) -> SoundShape:
    """The fixed soothe shape of one cue (every range collapsed to its one value)."""
    return SoundShape(
        tempo_bpm=(spec["tempo_bpm"],) * 2,
        pitch_hz=(spec["pitch_hz"],) * 2,
        length_s=(spec["length_s"],) * 2,
        gain_db=GAIN_DB,
    )


def blip_plan(spec: dict) -> BlirpPlan:
    """The one-event plan of a blip: a single chirp filling its length."""
    event = BlirpEvent(spec["event"], 0.0, spec["length_s"], spec["f0_hz"], spec["f1_hz"], 0, 0)
    return BlirpPlan(spec["length_s"], db_to_gain(spec["gain_db"]), (event,))


def render(spec: dict) -> np.ndarray:
    """The cue as 16-bit samples."""
    if "seed" in spec:
        samples = synthesize("blirp", shape(spec), random.Random(spec["seed"]), RATE_HZ)
    else:
        samples = render_blirp(blip_plan(spec), RATE_HZ)
    return np.round(samples * PCM_FULL_SCALE).astype(np.int16)


def events(spec: dict) -> list[str]:
    """The event kinds of a cue, in order."""
    plan = plan_blirp(shape(spec), random.Random(spec["seed"])) if "seed" in spec else None
    return [e.kind for e in (plan or blip_plan(spec)).events]


def wav_bytes(pcm: np.ndarray) -> bytes:
    buf = io.BytesIO()
    with wave.open(buf, "wb") as out:
        out.setnchannels(1)
        out.setsampwidth(2)
        out.setframerate(RATE_HZ)
        out.writeframes(pcm.astype("<i2").tobytes())
    return buf.getvalue()


def read_pcm(path: Path) -> np.ndarray:
    with wave.open(str(path), "rb") as src:
        return np.frombuffer(src.readframes(src.getnframes()), "<i2")


def vendored(rendered: dict[str, bytes]) -> dict:
    return {
        "made_by": "scripts/make_cue_sounds.py (RoboEmot's soothe synth, no third-party audio)",
        "license": "generated by this repository's code: the repository's own terms",
        "synth": "roboemot.soothe.synth.synthesize('blirp', shape, random.Random(seed), rate); "
        "a cue without a seed: render_blirp of its one event",
        "rate_hz": RATE_HZ,
        "gain_db": GAIN_DB,
        "cues": {
            name: {
                **spec,
                "events": events(spec),
                "file": f"{name}.wav",
                "sha256": hashlib.sha256(data).hexdigest(),
            }
            for name, (spec, data) in ((n, (CUES[n], rendered[n])) for n in CUES)
        },
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="compare, write nothing")
    args = parser.parse_args(argv)
    if args.check:
        bad = []
        for name, spec in CUES.items():
            path = OUT / f"{name}.wav"
            fresh = render(spec).astype(np.int32)
            if not path.exists():
                bad.append(f"{name}: missing")
                continue
            have = read_pcm(path).astype(np.int32)
            if have.shape != fresh.shape or int(np.max(np.abs(have - fresh))) > CHECK_TOLERANCE:
                bad.append(f"{name}: differs from a fresh render")
        for line in bad:
            print(line, file=sys.stderr)
        return 1 if bad else 0
    OUT.mkdir(parents=True, exist_ok=True)
    rendered = {name: wav_bytes(render(spec)) for name, spec in CUES.items()}
    for name, data in rendered.items():
        (OUT / f"{name}.wav").write_bytes(data)
    text = json.dumps(vendored(rendered), indent=2) + "\n"
    (OUT / "VENDORED.json").write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
